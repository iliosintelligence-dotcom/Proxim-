//! Golden vectors (engine-spec 9): the files on disk are replayed, regenerated and checked.
//! Any byte difference fails. Regenerate deliberately with
//! `PROXIM_BLESS=1 cargo run -p proxim-decide --example gen_golden` and review the diff.
#![allow(clippy::unwrap_used, clippy::indexing_slicing, clippy::expect_used)]

#[path = "../examples/support/fixtures.rs"]
mod fixtures;
#[path = "../examples/support/golden_scenarios.rs"]
mod golden_scenarios;
#[path = "../examples/support/manifest.rs"]
mod manifest;

use proxim_decide::golden::{build, parse, render, verify_json, verify_typed};
use proxim_decide::json::decide_json;
use proxim_decide::sha256::sha256_hex;
use proxim_types::{Outcome, ReasonCode};
use std::collections::BTreeSet;
use std::path::PathBuf;

fn golden_dir() -> PathBuf {
    core_dir().join("testdata/golden")
}

fn decide_files() -> Vec<(String, Vec<u8>)> {
    let dir = golden_dir().join("decide");
    let mut out = Vec::new();
    for e in std::fs::read_dir(&dir).unwrap() {
        let p = e.unwrap().path();
        if p.extension().is_some_and(|x| x == "json") {
            out.push((
                p.file_stem().unwrap().to_string_lossy().into_owned(),
                std::fs::read(&p).unwrap(),
            ));
        }
    }
    out.sort();
    out
}

const REQUIRED: [&str; 11] = [
    "drive_in_enter",
    "approach_fire_on_route",
    "drive_past_parallel_road",
    "opposite_carriageway",
    "standoff_suppressed",
    "consent_denied",
    "cap_exhaustion",
    "clock_goes_backwards",
    "malformed_fixes",
    "u_turn_before_anchor",
    "two_signposts_one_slot",
];

#[test]
fn golden_required_scenarios_exist() {
    let ids: BTreeSet<String> = decide_files().into_iter().map(|(id, _)| id).collect();
    for r in REQUIRED {
        assert!(ids.contains(r), "missing golden vector {r}");
    }
}

#[test]
fn golden_vectors_replay_byte_for_byte_with_typed_decide() {
    let files = decide_files();
    assert!(files.len() >= REQUIRED.len());
    for (id, bytes) in files {
        verify_typed(&bytes).unwrap_or_else(|e| panic!("{id}: {e}"));
    }
}

#[test]
fn golden_vectors_replay_byte_for_byte_through_decide_json() {
    // The conformance entry: every argument as canonical text, state threaded as text.
    for (id, bytes) in decide_files() {
        verify_json(&bytes, &decide_json).unwrap_or_else(|e| panic!("{id}: {e}"));
    }
}

#[test]
fn golden_regeneration_is_byte_identical_and_complete() {
    let scenarios = golden_scenarios::scenarios();
    let on_disk: BTreeSet<String> = decide_files().into_iter().map(|(id, _)| id).collect();
    let built: BTreeSet<String> = scenarios.iter().map(|s| s.id.clone()).collect();
    assert_eq!(
        on_disk, built,
        "every scenario has a file and every file a scenario"
    );
    for sc in scenarios {
        let text = render(&build(&sc).unwrap()).unwrap();
        let path = golden_dir().join("decide").join(format!("{}.json", sc.id));
        let disk = std::fs::read_to_string(&path).unwrap();
        assert!(
            disk == text,
            "{}: regenerated bytes differ from {} (len {} vs {}); bless only if the change is \
             intended and bump engine_spec for a behaviour change",
            sc.id,
            path.display(),
            text.len(),
            disk.len()
        );
    }
}

#[test]
fn golden_manifest_matches_the_files() {
    let dir = golden_dir();
    let want = manifest::render(&dir).unwrap();
    let disk = std::fs::read_to_string(dir.join("MANIFEST.json")).unwrap();
    assert!(
        disk == want,
        "MANIFEST.json is stale; run the generator with PROXIM_BLESS=1"
    );
    // The two table files are covered too (their bytes must not change silently).
    assert!(disk.contains("\"path\":\"frame_scale_table.json\""));
    assert!(disk.contains("\"path\":\"sincos_table.json\""));
    // And every listed hash is the hash of the file.
    let tree: serde_json::Value = serde_json::from_str(&disk).unwrap();
    for v in tree["vectors"].as_array().unwrap() {
        let bytes = std::fs::read(dir.join(v["path"].as_str().unwrap())).unwrap();
        assert_eq!(sha256_hex(&bytes), v["sha256"].as_str().unwrap());
    }
}

#[test]
fn golden_files_are_canonical_synthetic_and_carry_the_spec_header() {
    for (id, bytes) in decide_files() {
        let v = parse(&bytes).unwrap_or_else(|e| panic!("{id}: {e}"));
        assert_eq!(v.header.id, id);
        assert_eq!(v.header.kind, "decide");
        assert_eq!(v.header.engine_spec, proxim_types::ENGINE_SPEC);
        assert!(v.header.synthetic);
        assert_eq!(v.header.format, "proxim-golden/1");
        assert!(bytes.ends_with(b"\n") && !bytes.ends_with(b"\n\n"));
        let text = String::from_utf8(bytes).unwrap();
        assert!(
            !text[..text.len() - 1].contains('\n'),
            "one line plus the trailing newline"
        );
        assert!(!text.contains(" "), "canonical: no whitespace");
        assert!(
            !text.contains("null") && !text.contains('.'),
            "no null and no float"
        );
        // The hash of the state after every step is 64 lowercase hex digits.
        for s in &v.steps {
            let h = &s.expect.state_sha256;
            assert!(
                h.len() == 64
                    && h.bytes()
                        .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
            );
        }
    }
}

#[test]
fn golden_verifier_detects_every_kind_of_tampering() {
    let (_, bytes) = decide_files()
        .into_iter()
        .find(|(id, _)| id == "drive_in_enter")
        .unwrap();
    let text = String::from_utf8(bytes.clone()).unwrap();
    assert!(verify_typed(&bytes).is_ok());
    // 1. a changed output byte (a reason code)
    let t = text.replacen("\"NO_EVENT\"", "\"NOT_CLOSING\"", 1);
    assert!(verify_typed(t.as_bytes()).is_err());
    // 2. a changed state hash (flip one hex digit of the first one)
    let first_hash = text.find("\"state_sha256\":\"").unwrap() + "\"state_sha256\":\"".len();
    let mut t = text.clone().into_bytes();
    t[first_hash] = if t[first_hash] == b'0' { b'1' } else { b'0' };
    assert!(verify_typed(&t).is_err());
    // 3. a changed trace hash
    let tail = text.rfind("\"trace_sha256\":\"").unwrap() + "\"trace_sha256\":\"".len();
    let mut t = text.clone().into_bytes();
    t[tail] = if t[tail] == b'0' { b'1' } else { b'0' };
    assert!(verify_typed(&t).is_err());
    // 4. a changed input (fix accuracy) with the old expectations
    let t = text.replacen("\"acc_mm\":5000", "\"acc_mm\":5001", 1);
    assert!(verify_typed(t.as_bytes()).is_err());
    // 5. non-canonical bytes: whitespace, missing newline, a float, a reordered key
    assert!(verify_typed(text.replacen("{\"", "{ \"", 1).as_bytes()).is_err());
    assert!(verify_typed(text.trim_end().as_bytes()).is_err());
    assert!(
        verify_typed(
            text.replacen("\"acc_mm\":5000", "\"acc_mm\":5000.0", 1)
                .as_bytes()
        )
        .is_err()
    );
    // 6. a dropped step (the trace hash covers every step)
    let mut v = parse(&bytes).unwrap();
    v.steps.remove(5);
    assert!(verify_typed(render(&v).unwrap().as_bytes()).is_err());
    // 7. swapped steps
    let mut v = parse(&bytes).unwrap();
    v.steps.swap(2, 3);
    assert!(verify_typed(render(&v).unwrap().as_bytes()).is_err());
    // 8. the same checks through the JSON entry point
    let t = text.replacen("\"NO_EVENT\"", "\"NOT_CLOSING\"", 1);
    assert!(verify_json(t.as_bytes(), &decide_json).is_err());
    // 9. a wrong header
    let t = text.replacen("proxim-golden/1", "proxim-golden/2", 1);
    assert!(parse(t.as_bytes()).is_err());
    let t = text.replacen("\"synthetic\":true", "\"synthetic\":false", 1);
    assert!(parse(t.as_bytes()).is_err());
}

fn vector(id: &str) -> proxim_decide::golden::Vector {
    let (_, b) = decide_files().into_iter().find(|(i, _)| i == id).unwrap();
    parse(&b).unwrap()
}

fn fire_steps(v: &proxim_decide::golden::Vector) -> Vec<usize> {
    v.steps
        .iter()
        .enumerate()
        .filter(|(_, s)| {
            s.expect
                .output
                .decisions
                .iter()
                .any(|d| d.outcome == Outcome::Fire)
        })
        .map(|(i, _)| i)
        .collect()
}

fn any_reason(v: &proxim_decide::golden::Vector, r: ReasonCode) -> bool {
    v.steps.iter().any(|s| {
        let o = &s.expect.output;
        o.fix.reason == r
            || o.decisions.iter().any(|d| d.reason == r)
            || o.notes.iter().flatten().any(|n| n.reason == r)
    })
}

#[test]
fn golden_vectors_show_the_intended_behaviour() {
    // A blessed file cannot silently encode a regression: the story of each is asserted here.
    assert_eq!(fire_steps(&vector("drive_in_enter")), vec![19]);
    assert_eq!(fire_steps(&vector("approach_fire_on_route")), vec![32]);
    assert!(fire_steps(&vector("drive_past_parallel_road")).is_empty());
    assert!(fire_steps(&vector("opposite_carriageway")).is_empty());
    assert!(fire_steps(&vector("u_turn_before_anchor")).is_empty());
    let v = vector("standoff_suppressed");
    assert_eq!(v.steps[0].expect.output.fix.reason, ReasonCode::Suppressed);
    assert!(
        v.steps
            .iter()
            .take(47)
            .all(|s| s.expect.output.fix.reason == ReasonCode::Suppressed)
    );
    assert!(
        v.steps
            .iter()
            .take(47)
            .all(|s| s.expect.output.decisions.is_empty())
    );
    assert_eq!(
        fire_steps(&v),
        vec![54],
        "after the zone the circle works normally"
    );
    assert!(
        !any_reason(&v, ReasonCode::SensitiveStandoff),
        "no explain, no proximity"
    );
    assert!(any_reason(
        &vector("standoff_explained"),
        ReasonCode::SensitiveStandoff
    ));
    for id in ["consent_denied", "consent_unknown"] {
        let v = vector(id);
        assert!(fire_steps(&v).is_empty());
        assert!(
            v.steps
                .iter()
                .all(|s| s.expect.output.fix.reason == ReasonCode::ConsentDenied)
        );
    }
    assert!(
        vector("child_directed_disabled")
            .steps
            .iter()
            .all(|s| s.expect.output.fix.reason == ReasonCode::EngineDisabled)
    );
    let v = vector("cap_exhaustion");
    assert_eq!(
        fire_steps(&v).len(),
        3,
        "two on day one, one on the next local day"
    );
    assert!(any_reason(&v, ReasonCode::CapSignpostDay));
    let v = vector("clock_goes_backwards");
    assert!(any_reason(&v, ReasonCode::FixFromFuture));
    assert_eq!(fire_steps(&v), vec![3]);
    let v = vector("malformed_fixes");
    for r in [
        ReasonCode::FixInvalid,
        ReasonCode::FixMock,
        ReasonCode::FixAccuracyTooCoarse,
        ReasonCode::FixFromFuture,
        ReasonCode::FixOutOfOrder,
        ReasonCode::FixStale,
        ReasonCode::FixJump,
    ] {
        assert!(any_reason(&v, r), "{r:?}");
    }
    let v = vector("two_signposts_one_slot");
    assert_eq!(fire_steps(&v), vec![3]);
    assert!(any_reason(&v, ReasonCode::LostSlot) && any_reason(&v, ReasonCode::CapAppInterval));
    assert!(any_reason(
        &vector("unsupported_events"),
        ReasonCode::UnsupportedEvent
    ));
    assert!(any_reason(
        &vector("late_join_too_late"),
        ReasonCode::TooLateForLead
    ));
    assert!(fire_steps(&vector("late_join_too_late")).is_empty());
    assert!(any_reason(
        &vector("health_gates"),
        ReasonCode::HealthConsentMissing
    ));
    assert!(fire_steps(&vector("health_gates")).is_empty());
    // With the receipt the consent gate passes, but ENTER is P0 (500) and health's floor is 700
    // (spec 5.3, errata E-D-HEALTH): a health ENTER never fires in M1.
    let v = vector("health_with_receipt");
    assert!(fire_steps(&v).is_empty());
    assert!(any_reason(&v, ReasonCode::PathConfidenceLow));
    assert!(any_reason(&v, ReasonCode::TriggerInStandoff));
    assert!(fire_steps(&vector("boundary_jitter_never_enters")).is_empty());
    let v = vector("aged_clock_event_too_old");
    assert!(any_reason(&v, ReasonCode::EventTooOld) && fire_steps(&v).is_empty());
    let v = vector("superseded_and_ambiguous_revisions");
    assert_eq!(fire_steps(&v), vec![3]);
    assert!(any_reason(&v, ReasonCode::TriggerInvalid));
    // Three general fires; the health ENTER (h-1) no longer fires below its 700 floor (E-D-HEALTH).
    let v = vector("world_tour");
    assert_eq!(fire_steps(&v), vec![32, 63, 74]);
    assert!(any_reason(&v, ReasonCode::PathConfidenceLow));
}

/// The `core/` directory. `PROXIM_CORE_DIR` overrides the build machine's path
/// when the tests run on a device (Android emulator) with the tree copied over.
fn core_dir() -> std::path::PathBuf {
    std::env::var_os("PROXIM_CORE_DIR").map_or_else(
        || std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../.."),
        std::path::PathBuf::from,
    )
}
