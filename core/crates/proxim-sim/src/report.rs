//! Markdown report of a phone-simulator run (`core/testdata/sim/phone-simulator-results.md`).

use crate::phone::{MissKind, RunResult, World, duplicates, fit};
use alloc::collections::BTreeMap;
use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;
use core::fmt::Write;
use proxim_types::{Class, ReasonCode};

fn reason_text(r: ReasonCode) -> &'static str {
    match r {
        ReasonCode::PartnerCategoryBlocked => "category blocked by the app",
        ReasonCode::CategoryNotAccepted => "category not accepted by the app",
        ReasonCode::HealthConsentMissing => "no health consent in this app",
        ReasonCode::SenderBlocked => "sender blocked by the app",
        ReasonCode::SensitivityAboveCeiling => "too sensitive for the app",
        ReasonCode::TriggerInStandoff => "health advert placed inside a facility's 1 km standoff",
        ReasonCode::CapAppInterval => "app already showed an advert in the last 30 min",
        ReasonCode::CapSignpostDay => "advert already shown twice today",
        ReasonCode::CapSignpostWeek => "advert already shown five times this week",
        ReasonCode::LostSlot => "another advert won the slot",
        ReasonCode::EventTooOld => "event too old",
        ReasonCode::EventTooFar => "event too far",
        ReasonCode::PathConfidenceLow => "location evidence too weak for this advert",
        ReasonCode::PathTierLow => "movement evidence too weak for this advert",
        ReasonCode::BearingMismatch => "heading the wrong way",
        ReasonCode::NotClosing => "not moving towards the advert's anchor",
        ReasonCode::OffCorridor => "not on the advert's road",
        ReasonCode::SpeedOutOfBand => "speed outside the advert's band",
        ReasonCode::OutOfRange => "out of range",
        _ => "other",
    }
}

fn miss_text(k: MissKind) -> String {
    match k {
        MissKind::Policy(r) | MissKind::Paced(r) | MissKind::Path(r) => {
            format!("{} (`{}`)", reason_text(r), wire(r))
        }
        MissKind::NotTriggered => String::from("not on this phone's route, or never triggered"),
    }
}

fn wire(r: ReasonCode) -> String {
    serde_json::to_value(r)
        .ok()
        .and_then(|v| v.as_str().map(String::from))
        .unwrap_or_default()
}

fn clock(t_ms: i64) -> String {
    let s = t_ms.rem_euclid(86_400_000) / 1000;
    format!("{:02}:{:02}:{:02}", s / 3600, s / 60 % 60, s % 60)
}

fn name<T>(v: &[T], i: usize, f: impl Fn(&T) -> &'static str) -> &'static str {
    v.get(i).map_or("?", f)
}

/// The report for both routing modes. Pure: the same runs give the same bytes.
#[must_use]
#[allow(clippy::too_many_lines)]
pub fn markdown(world: &World, runs: &[RunResult]) -> String {
    let mut s = String::new();
    let app_name = |i: usize| name(&world.apps, i, |a| a.name);
    let ad_id = |i: usize| world.adverts.get(i).map_or("?", |a| a.signpost.id.as_str());
    let _ = writeln!(s, "# Phone simulator results\n");
    let _ = writeln!(
        s,
        "Generated by `cargo run -p proxim-sim --example phone_report`; checked by \
         `cargo test -p proxim-sim --test phone_sim`. Every number below comes from running the \
         real engine (`proxim_decide::decide`) inside each simulated partner app, one location \
         fix per second. How to read it: `docs/phone-simulator.md`.\n"
    );

    let _ = writeln!(s, "## Partner apps and what they accept\n");
    let _ = writeln!(
        s,
        "| App | What it is | Accepts | Blocks | Prefers (weight) |\n|---|---|---|---|---|"
    );
    for a in &world.apps {
        let p = &a.policy;
        let accepts = if p.child_directed == Some(true) {
            String::from("nothing (child-directed: the engine is off)")
        } else if p.categories_accepted.is_empty() {
            String::from("everything not blocked")
        } else {
            p.categories_accepted.join(", ")
        };
        let prefers: Vec<String> = p
            .category_affinity
            .iter()
            .map(|x| format!("{} ({})", x.category, x.weight_milli))
            .collect();
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | {} |",
            a.name,
            a.what,
            accepts,
            if p.categories_blocked.is_empty() {
                String::from("-")
            } else {
                p.categories_blocked.join(", ")
            },
            if prefers.is_empty() {
                String::from("-")
            } else {
                prefers.join(", ")
            }
        );
    }

    let _ = writeln!(s, "\n## Adverts\n");
    let _ = writeln!(
        s,
        "| Advert | Sender | Category | Where | Message | Best-fit app(s) |\n|---|---|---|---|---|---|"
    );
    for ad in &world.adverts {
        let fits: Vec<(usize, u16)> = world
            .apps
            .iter()
            .enumerate()
            .filter_map(|(i, a)| fit(&a.policy, &ad.signpost.category).map(|w| (i, w)))
            .collect();
        let best = fits.iter().map(|f| f.1).max();
        let best_apps: Vec<&str> = fits
            .iter()
            .filter(|f| Some(f.1) == best)
            .map(|f| app_name(f.0))
            .collect();
        let class = if ad.signpost.class == Class::Health {
            " (health)"
        } else {
            ""
        };
        let _ = writeln!(
            s,
            "| `{}` | {} | {}{} | {} | {} | {} |",
            ad.signpost.id.as_str(),
            ad.sender_name,
            ad.signpost.category,
            class,
            ad.place,
            ad.headline,
            if best_apps.is_empty() {
                String::from("none: no partner accepts it")
            } else {
                best_apps.join(", ")
            }
        );
    }

    let _ = writeln!(s, "\n## Phones\n");
    let _ = writeln!(
        s,
        "| Phone | Who | Apps installed | Journeys |\n|---|---|---|---|"
    );
    for p in &world.phones {
        let apps: Vec<String> = p
            .apps
            .iter()
            .map(|i| {
                let mut x = String::from(app_name(i.app));
                if !i.location {
                    x.push_str(" (location: no)");
                } else if i.health {
                    x.push_str(" (health: yes)");
                }
                x
            })
            .collect();
        let js: Vec<&str> = p
            .journeys
            .iter()
            .map(|&j| name(&world.journeys, j, |x| x.name))
            .collect();
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} |",
            p.name,
            p.persona,
            apps.join(", "),
            js.join("; ")
        );
    }

    for r in runs {
        let dups = duplicates(r);
        let reached: BTreeMap<usize, ()> = r.deliveries.iter().map(|d| (d.advert, ())).collect();
        let _ = writeln!(s, "\n## Routing: {}\n", r.routing.label());
        let _ = writeln!(
            s,
            "{} deliveries; {} of {} adverts reached at least one phone; {} duplicate(s) (same \
             advert from two apps on one phone).\n",
            r.deliveries.len(),
            reached.len(),
            world.adverts.len(),
            dups.len()
        );
        let _ = writeln!(s, "### What each phone showed\n");
        for (pi, p) in world.phones.iter().enumerate() {
            let _ = writeln!(s, "**{}**\n", p.name);
            let mine: Vec<_> = r.deliveries.iter().filter(|d| d.phone == pi).collect();
            if mine.is_empty() {
                let _ = writeln!(s, "- nothing");
            }
            for d in mine {
                let ad = world.adverts.get(d.advert);
                let _ = writeln!(
                    s,
                    "- {} {} showed `{}` ({}): \"{}\"",
                    clock(d.t_ms),
                    app_name(d.app),
                    ad_id(d.advert),
                    ad.map_or("?", |a| a.signpost.category.as_str()),
                    ad.map_or("?", |a| a.headline),
                );
            }
            for x in r.silent.iter().filter(|x| x.phone == pi) {
                let _ = writeln!(
                    s,
                    "- {} never ran the engine (`{}`)",
                    app_name(x.app),
                    wire(x.reason)
                );
            }
            let _ = writeln!(s);
        }
        let _ = writeln!(
            s,
            "### Why an app that received an advert did not show it\n"
        );
        let _ = writeln!(s, "| Phone | App | Advert | Reason |\n|---|---|---|---|");
        for m in r.misses.iter().filter(|m| m.kind != MissKind::NotTriggered) {
            let _ = writeln!(
                s,
                "| {} | {} | `{}` | {} |",
                name(&world.phones, m.phone, |p| p.name),
                app_name(m.app),
                ad_id(m.advert),
                miss_text(m.kind)
            );
        }
        let not_trig = r
            .misses
            .iter()
            .filter(|m| m.kind == MissKind::NotTriggered)
            .count();
        let _ = writeln!(
            s,
            "\nPlus {not_trig} (phone, app, advert) combinations where the advert was routed to \
             the app but the phone never passed it (not on that day's route)."
        );
        if !dups.is_empty() {
            let _ = writeln!(s, "\n### Duplicates\n");
            for (p, a, apps) in &dups {
                let names: Vec<&str> = apps.iter().map(|&i| app_name(i)).collect();
                let _ = writeln!(
                    s,
                    "- {}: `{}` from {}",
                    name(&world.phones, *p, |x| x.name),
                    ad_id(*a),
                    names.join(" and ")
                );
            }
        }
        let never: Vec<&str> = (0..world.adverts.len())
            .filter(|i| !reached.contains_key(i))
            .map(ad_id)
            .collect();
        let _ = writeln!(
            s,
            "\nNever delivered: {}.",
            if never.is_empty() {
                String::from("none")
            } else {
                never
                    .iter()
                    .map(|x| format!("`{x}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            }
        );
    }
    s
}
