export type GlyphName = keyof typeof glyphs;

export function PixelIcon({
  name,
  className = "size-5",
  ink = "currentColor",
  accent = "#0062ff",
}: {
  name: GlyphName;
  className?: string;
  ink?: string;
  accent?: string;
}) {
  const g = glyphs[name];
  return (
    <svg viewBox="0 0 9 9" className={className} shapeRendering="crispEdges" aria-hidden="true">
      {g.flatMap((row, y) =>
        row.split("").map((c, x) =>
          c === "." ? null : <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill={c === "o" ? accent : ink} />,
        ),
      )}
    </svg>
  );
}
